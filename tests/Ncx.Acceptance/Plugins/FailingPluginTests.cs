using Ncx.Acceptance.Cli;
using Ncx.Cli;
using Ncx.Cli.Commands;
using Ncx.Cli.History;
using Ncx.Compilers;
using Ncx.Core.Machine;
using Ncx.Core.Model;
using Ncx.Core.Parsing;
